from __future__ import annotations

import shutil
import subprocess
from abc import ABC, abstractmethod
from pathlib import Path
from typing import Any

from ..audio_utils import compute_residual, mix_audio
from ..models import ModelProcessRequest
from .context import PipelineExecutionContext


class BaseWorkflowNodeModule(ABC):
    NODE_TYPE = ""

    @abstractmethod
    def execute(
        self,
        *,
        context: PipelineExecutionContext,
        node: dict[str, Any],
        inputs: list[str],
    ) -> dict[str, str]:
        """Run this workflow node and return named audio outputs."""


class InputNodeModule(BaseWorkflowNodeModule):
    NODE_TYPE = "input"

    def execute(
        self,
        *,
        context: PipelineExecutionContext,
        node: dict[str, Any],
        inputs: list[str],
    ) -> dict[str, str]:
        _ = node
        _ = inputs
        return {"audio": str(context.prepared_path)}


class DenoiseNodeModule(BaseWorkflowNodeModule):
    NODE_TYPE = "denoise"

    def execute(
        self,
        *,
        context: PipelineExecutionContext,
        node: dict[str, Any],
        inputs: list[str],
    ) -> dict[str, str]:
        if not inputs:
            return {}

        data = node.get("data", {})
        model_name = data.get("model") or data.get("model_name") or "deepfilternet"
        model = context.get_model(model_name)
        request = ModelProcessRequest(
            input_audio_path=inputs[0],
            work_dir=context.tmpdir_path,
            node_id=node["id"],
            options={
                "attenuation_db": data.get("attenuation"),
                "model_base_dir": data.get("model_base_dir"),
                "input_is_prepared": True,
            },
        )
        result = model.process(request)

        clean_audio = result.get("audio")
        if clean_audio:
            noise_path = context.tmpdir_path / f"noise_{node['id']}.wav"
            residual = compute_residual(inputs[0], clean_audio, noise_path)
            if residual:
                result["noise"] = residual

        return result


class SeparationNodeModule(BaseWorkflowNodeModule):
    NODE_TYPE = "separation"

    def execute(
        self,
        *,
        context: PipelineExecutionContext,
        node: dict[str, Any],
        inputs: list[str],
    ) -> dict[str, str]:
        if not inputs:
            return {}

        data = node.get("data", {})
        model_name = data.get("model") or data.get("model_name") or "sepformer"
        model = context.get_model(model_name)
        request = ModelProcessRequest(
            input_audio_path=inputs[0],
            work_dir=context.tmpdir_path,
            node_id=node["id"],
            options={"output_subdir": f"sep_{node['id']}"},
        )
        result = model.process(request)

        speakers = [
            path
            for key, path in sorted(result.items())
            if key.startswith("speaker_") and isinstance(path, str) and path
        ]
        if speakers:
            mix_path = context.tmpdir_path / f"sep_{node['id']}" / "mix.wav"
            mix = mix_audio(speakers, mix_path)
            if mix:
                result["audio"] = mix

        return result


class CustomModelNodeModule(BaseWorkflowNodeModule):
    NODE_TYPE = "custom_model"

    def execute(
        self,
        *,
        context: PipelineExecutionContext,
        node: dict[str, Any],
        inputs: list[str],
    ) -> dict[str, str]:
        if not inputs:
            return {}

        data = node.get("data", {})
        model_name = data.get("model") or data.get("model_name")
        if not model_name:
            raise ValueError(
                f"Node '{node['id']}' is missing data.model (or data.model_name) for custom_model."
            )
        model = context.get_model(model_name)
        request = ModelProcessRequest(
            input_audio_path=inputs[0],
            work_dir=context.tmpdir_path,
            node_id=node["id"],
            options=data,
        )
        return model.process(request)


class MixerNodeModule(BaseWorkflowNodeModule):
    NODE_TYPE = "mixer"

    def execute(
        self,
        *,
        context: PipelineExecutionContext,
        node: dict[str, Any],
        inputs: list[str],
    ) -> dict[str, str]:
        _ = inputs
        data = node.get("data", {})
        mix_path = context.tmpdir_path / f"mixer_{node['id']}.wav"
        resolved = context.resolve_mixer_inputs(node["id"])
        paths = [path for path, _ in resolved]

        weights: list[float] = []
        for _, target_handle in resolved:
            weight = 1.0
            if target_handle == "in_1":
                try:
                    weight = float(data.get("spk1", 1))
                except (TypeError, ValueError):
                    weight = 1.0
            elif target_handle == "in_2":
                try:
                    weight = float(data.get("spk2", 1))
                except (TypeError, ValueError):
                    weight = 1.0
            weights.append(weight)

        mixed = mix_audio(paths, mix_path, weights)
        return {"audio": mixed} if mixed else {}


class ExportNodeModule(BaseWorkflowNodeModule):
    NODE_TYPE = "export"

    def execute(
        self,
        *,
        context: PipelineExecutionContext,
        node: dict[str, Any],
        inputs: list[str],
    ) -> dict[str, str]:
        if not inputs:
            return {}

        data = node.get("data", {})
        export_path = context.run_dir / f"export_{node['id']}.wav"
        shutil.copy(inputs[0], export_path)
        if data.get("format") == "mp3":
            export_path = self._convert_to_mp3(
                input_path=export_path,
                output_path=context.run_dir / f"export_{node['id']}.mp3",
            )
        return {"audio": str(export_path)}

    @staticmethod
    def _convert_to_mp3(input_path: Path, output_path: Path) -> Path:
        cmd = [
            "ffmpeg",
            "-y",
            "-i",
            str(input_path),
            "-codec:a",
            "libmp3lame",
            "-q:a",
            "2",
            str(output_path),
        ]
        subprocess.run(cmd, check=True, capture_output=True, text=True)
        return output_path


_NODE_MODULES: dict[str, BaseWorkflowNodeModule] = {}
_DEFAULT_MODULES_REGISTERED = False


def register_node_module(module: BaseWorkflowNodeModule) -> None:
    node_type = (module.NODE_TYPE or "").strip().lower()
    if not node_type:
        raise ValueError("Workflow node module must define NODE_TYPE.")
    _NODE_MODULES[node_type] = module


def register_default_node_modules() -> None:
    global _DEFAULT_MODULES_REGISTERED
    if _DEFAULT_MODULES_REGISTERED:
        return
    register_node_module(InputNodeModule())
    register_node_module(DenoiseNodeModule())
    register_node_module(SeparationNodeModule())
    register_node_module(CustomModelNodeModule())
    register_node_module(MixerNodeModule())
    register_node_module(ExportNodeModule())
    _DEFAULT_MODULES_REGISTERED = True


def get_node_module(node_type: str) -> BaseWorkflowNodeModule | None:
    register_default_node_modules()
    return _NODE_MODULES.get((node_type or "").strip().lower())
