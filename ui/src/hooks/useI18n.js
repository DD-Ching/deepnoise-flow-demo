function format(template, params) {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, key) => {
    if (params[key] === undefined) return match
    return String(params[key])
  })
}

export function useI18n(defaultLang = 'zh') {
  const [lang, setLangState] = useState(() => {
    if (typeof window === 'undefined') return defaultLang
    return localStorage.getItem(STORAGE_KEY) || defaultLang
  })

  const setLang = useCallback((next) => {
    setLangState(next)
    if (typeof window !== 'undefined') {
      localStorage.setItem(STORAGE_KEY, next)
    }
  }, [])

  const t = useCallback(
    (key, params) => {
      const dict = translations[lang] || translations.en
      const fallback = translations.en || {}
      const text = dict[key] || fallback[key] || key
      return format(text, params)
    },
    [lang]
  )

  const languages = useMemo(() => Object.keys(translations), [])

  return { lang, setLang, t, languages }
}
